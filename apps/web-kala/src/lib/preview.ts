import { jwtVerify } from 'jose';

export interface PreviewTokenPayload {
  sub: string;
  collection: 'landing-pages' | 'pages';
  slug: string;
  [key: string]: unknown;
}

/** Error khusus saat token preview ditolak (bukan gangguan server). */
export class PreviewAuthError extends Error {}

const DEFAULT_CMS_URL = 'https://admin.kalababyspa.com';

function resolveCmsUrl(runtimeEnv: Record<string, string | undefined> = {}) {
  const raw = runtimeEnv.PREVIEW_API_URL || runtimeEnv.PAYLOAD_URL || DEFAULT_CMS_URL;
  return raw.replace(/\/+$/, '');
}

/**
 * Verify signed JWT preview token generated by Payload CMS.
 * Tetap dipakai sebagai utilitas lokal; verifikasi utama kini dilakukan CMS.
 */
export async function verifyPreviewToken(token: string, secret?: string): Promise<PreviewTokenPayload> {
  if (!secret || secret.trim().length < 32) {
    throw new PreviewAuthError('Akses pratinjau ditolak: PREVIEW_SECRET belum disetel di environment.');
  }

  const key = new TextEncoder().encode(secret.trim());
  const { payload } = await jwtVerify(token, key, {
    issuer: 'kala-cms',
    audience: 'kala-preview',
  });
  return payload as unknown as PreviewTokenPayload;
}

/**
 * Ambil dokumen draft lewat endpoint CMS yang memverifikasi token preview.
 *
 * Dengan cara ini Worker tidak lagi menyimpan PREVIEW_SECRET/PREVIEW_API_KEY:
 * CMS adalah satu-satunya pemegang kredensial, sehingga preview tidak bisa
 * "patah" hanya karena environment variable Cloudflare belum ter-bind.
 */
export async function fetchPreviewDraftByToken(
  token: string,
  runtimeEnv: Record<string, string | undefined> = {},
) {
  const apiUrl = resolveCmsUrl(runtimeEnv);
  const endpoint = `${apiUrl}/api/preview-draft?token=${encodeURIComponent(token)}`;

  let res: Response;
  try {
    res = await fetch(endpoint, {
      headers: { Accept: 'application/json' },
      redirect: 'manual',
    });
  } catch (err) {
    throw new Error(`Tidak dapat menghubungi CMS: ${(err as Error).message}`);
  }

  if (res.status === 401 || res.status === 403) {
    throw new PreviewAuthError('Token pratinjau tidak valid atau sudah kedaluwarsa.');
  }

  if (!res.ok) {
    throw new Error(`Gagal mengambil draft dari CMS (${res.status} ${res.statusText}).`);
  }

  const data = await res.json().catch(() => null);
  if (!data?.doc) {
    throw new Error('CMS tidak mengembalikan dokumen draft.');
  }

  return data.doc;
}

/**
 * Fetch unpublished/draft document directly from Payload CMS using API Key.
 * Dipertahankan untuk kebutuhan server-side lain; preview memakai
 * `fetchPreviewDraftByToken` agar tidak bergantung pada secret di Worker.
 */
export async function fetchPreviewDraft(
  collection: string,
  id: string,
  runtimeEnv: Record<string, string | undefined> = {},
) {
  const apiUrl = resolveCmsUrl(runtimeEnv);
  const apiKey = runtimeEnv.PREVIEW_API_KEY;

  if (!apiKey) {
    throw new Error('Akses CMS ditolak: PREVIEW_API_KEY tidak disetel di environment web/Cloudflare.');
  }

  const cfId = runtimeEnv.PREVIEW_CF_ACCESS_CLIENT_ID;
  const cfSecret = runtimeEnv.PREVIEW_CF_ACCESS_CLIENT_SECRET;

  const headers: Record<string, string> = {
    'Content-Type': 'application/json',
    Authorization: `users API-Key ${apiKey.trim()}`,
  };

  if (cfId && cfSecret) {
    headers['CF-Access-Client-Id'] = cfId;
    headers['CF-Access-Client-Secret'] = cfSecret;
  }

  const res = await fetch(`${apiUrl}/api/${collection}/${id}?draft=true&depth=3`, {
    headers,
  });

  if (!res.ok) {
    throw new Error(`Gagal mengambil draft dari CMS (${res.status}: ${res.statusText})`);
  }

  return await res.json();
}
